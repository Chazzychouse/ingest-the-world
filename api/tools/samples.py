"""The sample corpus: `samples/manifest.json` made real in a gitignored cache.

    make samples                # the default set (under 2 GB)
    make samples LARGE=1        # plus the multi-GB stress files

Each file is downloaded from the primary source the manifest cites, generated by a seeded
generator here, or derived from another sample (a truncated copy), and is kept only if its
SHA-256 matches the manifest's. The manifest is the single home of what each file should become
once uploaded; the end-to-end suite (`tests/e2e/`) reads its expectations from there.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import io
import json
import random
import struct
import sys
from collections.abc import Callable, Iterator
from dataclasses import dataclass, field
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import Any, BinaryIO, Literal, cast

import httpx

from ingest_api.adapters.eicar_scanner import EICAR

REPO = Path(__file__).resolve().parents[2]
MANIFEST = REPO / "samples" / "manifest.json"
CACHE = REPO / "samples" / ".cache"
CHUNK = 1024 * 1024
DOWNLOAD_TIMEOUT_SECONDS = 60.0

type Json = dict[str, Any]
SampleSet = Literal["default", "large"]


@dataclass(frozen=True, slots=True)
class Expect:
    """What one upload of a sample should become. Absent fields aren't checked."""

    outcome: Literal["cataloged", "quarantined", "rejected"]
    reason: str | None = None  # the job's reason, for quarantine and rejection
    kind: str | None = None
    media_type: str | None = None
    extraction: str | None = None
    crs: str | None = None
    bbox: tuple[float, float, float, float] | None = None
    bbox_tolerance: float = 0.01  # degrees
    properties: Json = field(default_factory=dict[str, Any])  # a subset the item must carry


@dataclass(frozen=True, slots=True)
class Upload:
    """How the e2e suite uploads a sample: under which name, into which of its run's collections
    (uploads sharing a label share a collection), and with what declared checksum."""

    expect: Expect
    filename: str | None = None  # defaults to the sample's name
    collection: str = "main"
    declared_sha256: Literal["right", "wrong", "none"] = "right"


@dataclass(frozen=True, slots=True)
class Sample:
    name: str
    set: SampleSet
    sha256: str
    size: int
    uploads: tuple[Upload, ...]
    url: str | None = None  # downloaded from here, or
    generate: Json | None = None  # made by a generator here: {"by": name, ...params}, or
    derive: Json | None = None  # derived from another sample: {"from": name, "by": ...}

    @property
    def path(self) -> Path:
        return CACHE / self.name


def _expect(raw: Json) -> Expect:
    bbox = raw.get("bbox")
    return Expect(
        outcome=raw["outcome"],
        reason=raw.get("reason"),
        kind=raw.get("kind"),
        media_type=raw.get("media_type"),
        extraction=raw.get("extraction"),
        crs=raw.get("crs"),
        bbox=tuple(bbox) if bbox else None,
        bbox_tolerance=raw.get("bbox_tolerance", 0.01),
        properties=raw.get("properties", {}),
    )


def _sample(raw: Json) -> Sample:
    uploads = tuple(
        Upload(
            expect=_expect(u["expect"]),
            filename=u.get("filename"),
            collection=u.get("collection", "main"),
            declared_sha256=u.get("declared_sha256", "right"),
        )
        for u in raw["uploads"]
    )
    return Sample(
        name=raw["name"],
        set=raw["set"],
        sha256=raw["sha256"],
        size=raw["size"],
        uploads=uploads,
        url=raw.get("source", {}).get("url"),
        generate=raw.get("generate"),
        derive=raw.get("derive"),
    )


def load(manifest: Path = MANIFEST) -> list[Sample]:
    raw = cast(Json, json.loads(manifest.read_text()))
    return [_sample(s) for s in raw["samples"]]


def selected(samples: list[Sample], *, large: bool) -> list[Sample]:
    return [s for s in samples if large or s.set == "default"]


# -- generators ------------------------------------------------------------------------------
# Each writes deterministic bytes, so its output has a fixed checksum in the manifest.

GLB_HEADER = struct.Struct("<4sII")
GLB_CHUNK = struct.Struct("<II")
GLB_JSON, GLB_BIN = 0x4E4F534A, 0x004E4942
FLOAT, VEC3_BYTES = 5126, 12
# Positions are one block of a seeded point grid, repeated; min and max are the block's.
GLB_BLOCK_VERTICES = 87_381  # 3 per triangle, and just under 1 MiB of positions


def _glb_block(rng: random.Random) -> tuple[bytes, list[float], list[float]]:
    points = [(rng.uniform(-50, 50), rng.uniform(0, 20), rng.uniform(-50, 50)) for _ in range(3)]
    vertices = [points[i % 3] for i in range(GLB_BLOCK_VERTICES)]
    block = b"".join(struct.pack("<3f", *v) for v in vertices)
    packed = [struct.unpack("<3f", struct.pack("<3f", *p)) for p in points]  # as float32
    return (
        block,
        [min(axis) for axis in zip(*packed, strict=True)],
        [max(axis) for axis in zip(*packed, strict=True)],
    )


def generate_glb(out: BinaryIO, params: Json) -> None:
    """A valid glTF 2.0 binary with one triangle mesh whose binary chunk is `mib` MiB, give or
    take a block: the file's size is all geometry, its header a few hundred bytes."""
    rng = random.Random(params["seed"])  # noqa: S311 - seeded on purpose: fixed checksums
    block, low, high = _glb_block(rng)
    blocks = params["mib"] * CHUNK // len(block)
    vertices = blocks * GLB_BLOCK_VERTICES
    document = {
        "asset": {"version": "2.0", "generator": "ingest-the-world samples"},
        "scene": 0,
        "scenes": [{"nodes": [0]}],
        "nodes": [{"mesh": 0}],
        "meshes": [{"primitives": [{"attributes": {"POSITION": 0}}]}],
        "accessors": [
            {
                "bufferView": 0,
                "componentType": FLOAT,
                "count": vertices,
                "type": "VEC3",
                "min": low,
                "max": high,
            }
        ],
        "bufferViews": [{"buffer": 0, "byteLength": vertices * VEC3_BYTES}],
        "buffers": [{"byteLength": vertices * VEC3_BYTES}],
    }
    text = json.dumps(document, separators=(",", ":")).encode()
    text += b" " * (-len(text) % 4)
    binary = blocks * len(block)
    total = GLB_HEADER.size + 2 * GLB_CHUNK.size + len(text) + binary
    out.write(GLB_HEADER.pack(b"glTF", 2, total))
    out.write(GLB_CHUNK.pack(len(text), GLB_JSON) + text)
    out.write(GLB_CHUNK.pack(binary, GLB_BIN))
    for _ in range(blocks):
        out.write(block)


def _readings(params: Json) -> Iterator[dict[str, str | float]]:
    """Seeded sensor readings: a few devices sampling temperature and humidity every minute."""
    rng = random.Random(params["seed"])  # noqa: S311 - seeded on purpose: fixed checksums
    start = datetime(2026, 1, 1, tzinfo=UTC)
    for minute in range(params["minutes"]):
        at = (start + timedelta(minutes=minute)).isoformat()
        for device in range(params["devices"]):
            yield {
                "device_id": f"kit-{device:03d}",
                "observed_at": at,
                "temperature_c": round(rng.gauss(21, 2), 2),
                "humidity_pct": round(rng.uniform(30, 60), 1),
            }


def generate_readings_csv(out: BinaryIO, params: Json) -> None:
    text = io.TextIOWrapper(out, encoding="utf-8", newline="")
    writer = csv.DictWriter(text, ["device_id", "observed_at", "temperature_c", "humidity_pct"])
    writer.writeheader()
    writer.writerows(_readings(params))
    text.flush()
    text.detach()


def generate_readings_jsonl(out: BinaryIO, params: Json) -> None:
    for row in _readings(params):
        out.write(json.dumps(row).encode() + b"\n")


def generate_eicar(out: BinaryIO, _: Json) -> None:
    out.write(EICAR)


GENERATORS: dict[str, Callable[[BinaryIO, Json], None]] = {
    "glb": generate_glb,
    "readings-csv": generate_readings_csv,
    "readings-jsonl": generate_readings_jsonl,
    "eicar": generate_eicar,
}


def derive_truncated(out: BinaryIO, source: Path, params: Json) -> None:
    """The first `keep_bytes` of another sample: a transfer cut short, committed anyway."""
    remaining = params["keep_bytes"]
    with source.open("rb") as file:
        for _ in range(remaining // CHUNK + 1):  # bounded: one pass per chunk kept
            chunk = file.read(min(CHUNK, remaining))
            if not chunk:
                break
            out.write(chunk)
            remaining -= len(chunk)


# -- fetching --------------------------------------------------------------------------------


class Mismatch(Exception):
    """A sample's bytes aren't the ones the manifest names."""


def sha256_of(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as file:
        for chunk in iter(lambda: file.read(CHUNK), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _download(sample: Sample, url: str, out: BinaryIO) -> None:
    with httpx.stream("GET", url, follow_redirects=True, timeout=DOWNLOAD_TIMEOUT_SECONDS) as r:
        r.raise_for_status()
        written = 0
        for chunk in r.iter_bytes(CHUNK):
            written += len(chunk)
            if written > sample.size:  # bounded by the size the manifest expects
                raise Mismatch(f"{sample.name}: {url} sent more than {sample.size} bytes")
            out.write(chunk)


def _make(sample: Sample, by_name: dict[str, Sample], out: BinaryIO) -> None:
    if sample.url is not None:
        _download(sample, sample.url, out)
    elif sample.generate is not None:
        GENERATORS[sample.generate["by"]](out, sample.generate)
    elif sample.derive is not None:
        source = by_name[sample.derive["from"]]
        if not source.path.exists():
            raise Mismatch(f"{sample.name} derives from {source.name}, which isn't fetched")
        derive_truncated(out, source.path, sample.derive)
    else:
        raise Mismatch(f"{sample.name} has no source, generator or derivation")


def fetch(sample: Sample, by_name: dict[str, Sample]) -> str:
    """Makes `sample.path` hold exactly the manifest's bytes; returns what it did."""
    if sample.path.exists() and sha256_of(sample.path) == sample.sha256:
        return "cached"
    partial = sample.path.with_name(sample.path.name + ".part")
    with partial.open("wb") as out:
        _make(sample, by_name, out)
    actual = sha256_of(partial)
    if actual != sample.sha256 or partial.stat().st_size != sample.size:
        partial.unlink()
        raise Mismatch(f"{sample.name}: got sha256 {actual}, manifest says {sample.sha256}")
    partial.replace(sample.path)
    return "fetched" if sample.url else "made"


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="Fetch and verify the sample corpus.")
    parser.add_argument("--large", action="store_true", help="include the multi-GB samples")
    args = parser.parse_args(argv)
    samples = load()
    by_name = {s.name: s for s in samples}
    CACHE.mkdir(parents=True, exist_ok=True)
    failed = 0
    # Derived samples come after their sources.
    for sample in sorted(selected(samples, large=args.large), key=lambda s: s.derive is not None):
        try:
            print(f"{fetch(sample, by_name):<8} {sample.name}", flush=True)
        except (Mismatch, httpx.HTTPError, OSError) as exc:
            failed += 1
            print(f"FAILED   {sample.name}: {exc}", flush=True)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
