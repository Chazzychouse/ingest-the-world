INSERT INTO demo_items
    (collection_id, filename, kind, media_type, size_bytes, created_at, tags, extraction, crs,
     bbox, properties, raise_to)
SELECT 'site-survey-alpha',
       format('alpha_ortho_2cm_r%s_c%s.tif', r, c),
       'raster', 'image/tiff',
       180000000 + (r * 7 + c * 13) % 11 * 4000000,
       timestamptz '2025-06-16 14:00:00Z' + (r * 6 + c) * interval '5 hours 17 minutes',
       '{ortho,rgb,tile}', 'extracted', 'EPSG:32613',
       ARRAY[w, n - 0.0029, w + 0.0037, n],
       jsonb_build_object(
           'raster:driver', 'GTiff', 'proj:shape', jsonb_build_array(16000, 15600),
           'raster:band_count', 4,
           'raster:bands', '[{"data_type": "uint8", "nodata": null}, {"data_type": "uint8", "nodata": null},
                             {"data_type": "uint8", "nodata": null}, {"data_type": "uint8", "nodata": null}]'::jsonb,
           'proj:transform', jsonb_build_array(0.02, 0.0, 496600 + c * 312, 0.0, -0.02, 4493660 - r * 320)),
       CASE WHEN (r, c) IN ((3, 4), (3, 5)) THEN 'CUI' END
FROM generate_series(0, 4) AS r, generate_series(0, 5) AS c,
     LATERAL (SELECT -105.0400 + c * 0.0037 AS w, 40.5938 - r * 0.0029 AS n) AS origin;

-- Ids are derived from the name, so a rerun finds the items it made before.
CREATE TEMPORARY TABLE demo_ids ON COMMIT DROP AS
SELECT md5('demo:' || collection_id || '/' || filename)::uuid AS id, d.*
FROM demo_items d;

INSERT INTO ingest.uploads
    (id, collection_id, filename, size_bytes, content_type, sha256, tags, blob_name, status,
     created_by, created_at, url_expires_at)
SELECT id, collection_id, filename, size_bytes, media_type,
       encode(sha256(convert_to(id::text, 'UTF8')), 'hex'), tags,
       format('%s/%s/%s', collection_id, replace(id::text, '-', ''), filename), 'cataloged',
       'seed', created_at - interval '3 minutes', created_at + interval '57 minutes'
FROM demo_ids
ON CONFLICT (id) DO NOTHING;

INSERT INTO catalog.items
    (id, collection_id, kind, media_type, filename, size_bytes, sha256, raw_blob, marking, tags,
     created_by, created_at, extraction, extracted_bytes, crs, footprint, properties)
SELECT d.id, d.collection_id, d.kind, d.media_type, d.filename, d.size_bytes, u.sha256,
       u.blob_name, coalesce(d.raise_to, c.marking), d.tags, 'seed', d.created_at,
       d.extraction, CASE WHEN d.extraction = 'unsupported' THEN 0 ELSE 65536 END, d.crs,
       ST_MakeEnvelope(d.bbox[1], d.bbox[2], d.bbox[3], d.bbox[4], 4326), d.properties
FROM demo_ids d
JOIN ingest.uploads u ON u.id = d.id
JOIN catalog.collections c ON c.id = d.collection_id
ON CONFLICT (id) DO NOTHING;
