-- Demo catalog for the local stack: items with footprints, for the map and search. Loaded after
-- dev.sql by `migrate --demo`; tests never load it, so they start from an empty catalog.
-- Idempotent; never run against production.
--
-- The items look like the pipeline's output: kinds and media types the classifier assigns,
-- properties shaped like the readers' (`proj:`, `raster:`, `pc:`, `table:`, `mesh:`), and a
-- footprint only where a reader would find one. Their originals were never uploaded, so they
-- have no bytes in storage.
--
-- What it exercises, beyond volume (~90 items, several pages of search):
--   * footprints from a single sample point and 300 m drone tiles to the whole globe;
--   * a dense tiled orthomosaic (site-survey-alpha) and scenes that overlap across collections;
--   * Pacific surveys either side of 180°, for a search box that crosses it;
--   * the far north and south, past where Web Mercator draws;
--   * items marked CUI in UNCLASSIFIED collections (ACC-3), visible to alice and carol, not bob;
--   * items with no footprint (tables, meshes, reports) and every extraction outcome.

